import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

import { catalog } from '@run-planner/hades2-catalog';
import { EXECUTION_CATALOG_VERSION } from '../../src/execution-plan';
import { snapModeledTraitKeys } from '../../src/execution-plan/modeled-traits';

const modulePath = join(
  dirname(fileURLToPath(import.meta.url)),
  '../../../../game-module/src/modeled_traits.lua',
);
/** `npm run fixtures:modeled-traits` rewrites the module file through this one path. */
const rewrite = process.env.RUN_PLANNER_WRITE_MODELED_TRAITS === '1';

function rendered(): string {
  const keys = snapModeledTraitKeys(catalog);
  return [
    '-- Generated by `npm run fixtures:modeled-traits` from the planner catalog; do not edit.',
    '-- The in-run traits snap restores; every other trait stays live.',
    'return {',
    `    catalogVersion = "${EXECUTION_CATALOG_VERSION}",`,
    '    traits = {',
    ...keys.map((key) => `        "${key}",`),
    '    },',
    '}',
    '',
  ].join('\n');
}

describe('modelled traits module', () => {
  it('matches the catalog', () => {
    if (rewrite) writeFileSync(modulePath, rendered());
    expect(readFileSync(modulePath, 'utf8')).toBe(rendered());
  });

  it('leaves Arcana, Chaos, costumes, Gift Gift Gift and Spells to their own steps', () => {
    const keys = new Set(snapModeledTraitKeys(catalog));
    for (const key of [
      'MetaToRunMetaUpgrade',
      'ChaosHealthCurse',
      'ChaosHealthBlessing',
      'AgilityCostume',
      'EchoRepeatKeepsakeBoon',
      'SpellPotionTrait',
    ])
      expect(keys.has(key), key).toBe(false);
    expect(keys.has('ZeusWeaponBoon')).toBe(true);
  });
});
