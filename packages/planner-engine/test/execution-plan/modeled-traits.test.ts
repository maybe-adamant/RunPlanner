import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

import { catalog } from '@run-planner/hades2-catalog';
import { EXECUTION_CATALOG_VERSION } from '../../src/execution-plan/model';
import { snapModeledTraitKeys } from '../../src/execution-plan/modeled-traits';

const modulePath = join(
  dirname(fileURLToPath(import.meta.url)),
  '../../../../game-module/src/modeled_traits.lua',
);
/** `npm run fixtures:modeled-traits` rewrites the module file through this one path. */
const rewrite = process.env.RUN_PLANNER_WRITE_MODELED_TRAITS === '1';

/** The traits the game removes in combat, as their armor breaks or dodge decays: the planner keeps them. */
function removedInCombat(): readonly string[] {
  return catalog.traits.values
    .filter((trait) => trait.combatRemoval !== undefined)
    .map((trait) => trait.key)
    .sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
}

function rendered(): string {
  const keys = snapModeledTraitKeys(catalog);
  return [
    '-- Generated by `npm run fixtures:modeled-traits` from the planner catalog; do not edit.',
    '-- `traits`: the in-run traits snap restores; every other trait stays live.',
    '-- `removedInCombat`: traits the game removes as armor breaks or dodge decays, which the',
    '-- planner, assuming no damage, keeps; neither conformance nor snap judges them.',
    'return {',
    `    catalogVersion = "${EXECUTION_CATALOG_VERSION}",`,
    '    traits = {',
    ...keys.map((key) => `        "${key}",`),
    '    },',
    '    removedInCombat = {',
    ...removedInCombat().map((key) => `        ${key} = true,`),
    '    },',
    '}',
    '',
  ].join('\n');
}

describe('modelled traits module', () => {
  it('matches the catalog', () => {
    if (rewrite) writeFileSync(modulePath, rendered());
    expect(readFileSync(modulePath, 'utf8')).toBe(rendered());
  });

  it('leaves Arcana, Chaos, costumes, Gift Gift Gift and Spells to their own steps', () => {
    const keys = new Set(snapModeledTraitKeys(catalog));
    for (const key of [
      'MetaToRunMetaUpgrade',
      'ChaosHealthCurse',
      'ChaosHealthBlessing',
      'AgilityCostume',
      'EchoRepeatKeepsakeBoon',
      'SpellPotionTrait',
    ])
      expect(keys.has(key), key).toBe(false);
    expect(keys.has('ZeusWeaponBoon')).toBe(true);
  });

  it('lists the dresses, Icarus coatings and Evade Evade Evade as removed in combat', () => {
    expect(removedInCombat()).toEqual([
      'AgilityCostume',
      'BreakExplosiveArmorBoon',
      'BreakInvincibleArmorBoon',
      'CastDamageCostume',
      'DiminishingDodgeBoon',
      'EscalatingCostume',
      'HighArmorCostume',
      'IncomeCostume',
      'ManaCostume',
      'SpellCostume',
      'VitalityCostume',
    ]);
  });
});
