// Native inherited defaults: no ramp/escalation, room depth, unrestricted
// highlight, cross-wave counterpart exclusion. Each concrete row names its
// effective wave/type/elite bounds; NPCs do not borrow another NPC's policy.
function generation(data: GenerationDeclaration) {
  return {
    key: 'generatedComposition',
    label: 'Composition',
    selection: {
      kind: 'generated',
      choices: data.pool.map(withMenaceLabels),
      preparation: data.preparation ?? 'roomEntry',
      waveCount: { min: data.waves[0], max: data.waves[1] },
      types: {
        min: data.minTypes,
        max: data.maxTypes,
        cap: data.cap,
        depthRamp: data.ramp ?? 0,
        depthAxis: data.encounterDepth ? 'biomeEncounterDepth' : 'biomeDepthCache',
        escalate: data.escalate ?? false,
        ...(data.hardCap === undefined ? {} : { hardCap: data.hardCap }),
      },
      maxEliteTypes: data.eliteTypes,
      blockHighlightElites: data.blockHighlightElites ?? false,
      blockFangsAttributes: data.blockFangsAttributes ?? false,
      ...(data.blockMenace ? { blockMenace: true } : {}),
      blockTypesAcrossWaves: true,
      fixedEnemies: (data.fixedEnemies ?? []).map(withMenaceLabels),
      fangs: { perks: fangsPerks },
      budget: {
        base: 0,
        depthRamp: 0,
        depthAxis: 'biomeDepthCache',
        modifier: 0,
        multiplier: 1,
        minimum: 10,
      },
      maxTypesPerGroup: data.groups ?? {},
    } satisfies GeneratedEncounterSelection,
  } as const;
}

