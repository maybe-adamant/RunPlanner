import type {
  EncounterEnemyChoice,
  GeneratedEncounterSelection,
} from '@run-planner/engine/catalog-schema';
import { fixedFieldsEnemies, generatedEnemyPools as pools } from './enemies';

interface GenerationDeclaration {
  readonly preparation?: GeneratedEncounterSelection['preparation'];
  readonly pool: readonly EncounterEnemyChoice[];
  readonly waves: readonly [number, number];
  readonly minTypes: number;
  readonly maxTypes: number;
  readonly cap: number;
  readonly eliteTypes: number;
  readonly ramp?: number;
  readonly encounterDepth?: boolean;
  readonly escalate?: boolean;
  readonly hardCap?: number;
  readonly blockHighlightElites?: boolean;
  readonly fixedEnemies?: readonly EncounterEnemyChoice[];
  readonly groups?: GeneratedEncounterSelection['maxTypesPerGroup'];
}

// Native inherited defaults: no ramp/escalation, room depth, unrestricted
// highlight, cross-wave counterpart exclusion. Each concrete row names its
// effective wave/type/elite bounds; NPCs do not borrow another NPC's policy.
function generation(data: GenerationDeclaration) {
  return {
    key: 'generatedComposition',
    label: 'Composition',
    selection: {
      kind: 'generated',
      choices: data.pool,
      preparation: data.preparation ?? 'roomEntry',
      waveCount: { min: data.waves[0], max: data.waves[1] },
      types: {
        min: data.minTypes,
        max: data.maxTypes,
        cap: data.cap,
        depthRamp: data.ramp ?? 0,
        depthAxis: data.encounterDepth ? 'biomeEncounterDepth' : 'biomeDepthCache',
        escalate: data.escalate ?? false,
        ...(data.hardCap === undefined ? {} : { hardCap: data.hardCap }),
      },
      maxEliteTypes: data.eliteTypes,
      blockHighlightElites: data.blockHighlightElites ?? false,
      blockTypesAcrossWaves: true,
      fixedEnemies: data.fixedEnemies ?? [],
      maxTypesPerGroup: data.groups ?? {},
    } satisfies GeneratedEncounterSelection,
  } as const;
}

