import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import * as prettier from 'prettier';

/**
 * Regenerates the visible centre of each artwork a room map marker can hold:
 *
 *   npm run planner:map-marker-artwork
 *
 * Map markers centre an icon's box in their ring, but the artwork's
 * transparent padding is uneven, so its visible shape sits off the box's
 * centre. The visible shape is the bounding box of the pixels at least half
 * opaque, which ignores soft glows; its centre is recorded as a fraction of
 * the square the icon is contained in. Reads images through ImageMagick.
 */

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const artworkRoot = join(repositoryRoot, 'apps/planner/src/ui/artwork');
const outputPath = join(
  repositoryRoot,
  'apps/planner/src/ui/editor/biome/room-map/mapMarkerArtworkCentres.ts',
);

/** The artwork folders map markers draw from: rewards and boons, room objects, NPCs, the reroll die. */
export const markerArtworkFolders = Object.freeze([
  'rewards/assets',
  'room-objects/assets',
  'npcs/assets',
  'rerolls/assets',
]);

const opaque = 128;

const round = (value) => Math.round(value * 1e3) / 1e3;

function imageMagick(args) {
  for (const command of ['magick', 'convert']) {
    try {
      return execFileSync(command, args, { maxBuffer: 1 << 28 });
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error;
    }
  }
  throw new Error('ImageMagick (magick or convert) is required to read the artwork');
}

/** The visible centre of one RGBA image, in the square that contains it. */
export function visibleCentre(width, height, rgba) {
  let left = width;
  let top = height;
  let right = -1;
  let bottom = -1;
  for (let y = 0; y < height; y += 1)
    for (let x = 0; x < width; x += 1) {
      if (rgba[(y * width + x) * 4 + 3] < opaque) continue;
      left = Math.min(left, x);
      right = Math.max(right, x);
      top = Math.min(top, y);
      bottom = Math.max(bottom, y);
    }
  if (right < 0) return [0.5, 0.5];
  const side = Math.max(width, height);
  return [
    round(((left + right + 1) / 2 + (side - width) / 2) / side),
    round(((top + bottom + 1) / 2 + (side - height) / 2) / side),
  ];
}

function measure(path) {
  const [width, height] = imageMagick([path, '-format', '%w %h', 'info:'])
    .toString()
    .trim()
    .split(' ')
    .map(Number);
  const rgba = imageMagick([path, '-depth', '8', 'rgba:-']);
  if (rgba.length !== width * height * 4) throw new Error(`Unexpected pixel data for ${path}`);
  return visibleCentre(width, height, rgba);
}

async function main() {
  const entries = markerArtworkFolders.flatMap((folder) =>
    readdirSync(join(artworkRoot, folder))
      .filter((name) => /\.(avif|png|webp)$/.test(name))
      .sort()
      .map((name) => [`${folder}/${name}`, measure(join(artworkRoot, folder, name))]),
  );
  const source = `// Generated by scripts/measure-map-marker-artwork.mjs from the artwork images.

/**
 * Each map-marker artwork's visible centre, by its path under the artwork
 * folder, as fractions of the square the icon is contained in.
 */
export const mapMarkerArtworkCentres: Readonly<Record<string, readonly [number, number]>> =
  Object.freeze(${JSON.stringify(Object.fromEntries(entries))});
`;
  const options = (await prettier.resolveConfig(outputPath)) ?? {};
  writeFileSync(outputPath, await prettier.format(source, { ...options, filepath: outputPath }));
  process.stdout.write(`Wrote ${entries.length} artwork centres to ${outputPath}\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
